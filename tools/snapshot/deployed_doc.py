#!/usr/bin/env python3
"""Render docs/DEPLOYED-STATE.md from the checked snapshots (no RPC).

Inputs: snapshots/deployed/<chain>/state.json, snapshots/deployed/provenance.json,
tests/fixtures/legacy/manifest.json. Usage: deployed_doc.py [--check]
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))

import common  # noqa: E402

OUT = common.repo_path("docs", "DEPLOYED-STATE.md")
PHASES = {0: "OPEN", 1: "LOCKED", 2: "SETTLE_PROPOSED", 3: "SETTLED"}


def short(a):
    return f"`{a[:10]}…{a[-4:]}`" if a else "—"


def source_identity(prov, rel):
    r = prov["records"].get(rel, {})
    out = []
    for k, s in sorted(r.get("sources", {}).items()):
        if not k.startswith("project/"):
            continue
        g = s.get("git")
        out.append(f"`{k[8:]}` " + (f"blob `{g['blob'][:8]}` (introduced `{g['introduced_in']}`)" if g
                                    else "**no committed blob** (metadata-only)"))
    rc = r.get("recompile", {}).get("status", "NOT RUN")
    oc = r.get("onchain", {})
    oc_s = "MATCH" if oc.get("equals_record_runtime") else ("—" if not oc else "proxy-address record")
    return "; ".join(out) or "—", rc, oc_s


def render():
    prov = common.read_json(common.repo_path("snapshots", "deployed", "provenance.json"))
    lines = ["# Deployed state", "",
             "Generated by `tools/snapshot/deployed_doc.py` from `snapshots/deployed/` (pinned blocks, "
             "checked with `--check`). Facts only; the migration design lives in the research repository.", ""]
    for chain in ("mainnet", "testnet"):
        st = common.read_json(common.repo_path("snapshots", "deployed", chain, "state.json"))
        lines += [f"## {chain} (chain {st['chain_id']}) at block {st['block']}", "",
                  f"ProxyAdmin {short(st['proxy_admin']['address'])} (OZ v4), owner {short(st['proxy_admin']['owner'])}.", ""]
        lines += ["| Proxy | Implementation | Expected | `_initialized` | Owner | Paused | Admin = ProxyAdmin |",
                  "|---|---|---|---|---|---|---|"]
        for p, x in st["proxies"].items():
            lines.append(f"| {x['name']} {short(p)} | {short(x['implementation'])} | "
                         f"{'yes' if x['implementation_is_expected'] else '**NO**'} | {x['initialized_version']} | "
                         f"{short(x['owner'])} | {x['paused']} | {x['admin_is_proxy_admin']} |")
        lines += ["", "| Beacon | Owner | Implementation |", "|---|---|---|"]
        for b, x in st["beacons"].items():
            lines.append(f"| {x['role']} {short(b)} | {short(x['owner'])} | {short(x['implementation'])} |")
        for f, x in st["factories"].items():
            lines += ["", f"Factory {short(f)}: owner {short(x['owner'])}, paused {x['paused']}, {x['vault_count']} vault(s).", "",
                      "| # | Vault | Phase | Round | TMA (wei) | Supply | Asset balance |", "|---|---|---|---|---|---|---|"]
            for v in x["vaults"]:
                lines.append(f"| {v['index']} | {short(v['vault'])} | {PHASES.get(v['phase'], v['phase'])} | {v['roundIndex']} | "
                             f"{v['totalManagedAssets']} | {v['totalSupply']} | {v['asset_balance']} |")
        a = st["stpros"]
        rel = a["PRE4_relations"]
        lines += ["", "StPROS accounting (wei):", "",
                  f"- S totalSupply {a['S_totalSupply']}; E escrow {a['E_escrow']}; R {a['R_totalCanWithdrawAmount']}",
                  f"- Q {a['Q_queuedWithdrawal']}; C {a['C_completedWithdrawal']}; W (WPROS held) {a['W_wprosBalance']}; native {a['native_balance']}",
                  f"- maxWithdrawCount {a['maxWithdrawCount']}; unbondingPeriod {a['unbondingPeriod']}; oracle pool(WPROS) {a['oracle_pool_wpros']}",
                  f"- Relations: R = Q − C **{rel['R_eq_Q_minus_C']}**; E ≥ R **{rel['E_ge_R']}**; "
                  f"W − R ≥ S − E **{rel['W_minus_R_ge_S_minus_E']}**; pool = (0,0) **{rel['pool_is_zero']}**", ""]
        if "safe" in st:
            s = st["safe"]
            lines += [f"Safe {short(s['address'])}: threshold {s['threshold']} of {len(s['owners'])}, nonce {s['nonce']}, "
                      f"modules {s['modules'] or 'none'}, guard {short(s['guard'])}.", ""]
        lines += [f"WPROS {short(st['wpros']['address'])}: runtime keccak `{st['wpros']['code']['keccak256'][:18]}…` "
                  f"({st['wpros']['code']['size']} bytes).", ""]
    lines += ["## Source identity of recorded implementations", "",
              "Recompile = solc(metadata sources, metadata settings) equals the recorded creation and runtime "
              "bytecode; on-chain = recorded runtime equals the code at the address at the pinned block.", "",
              "| Record | Project sources | Recompile | On-chain |", "|---|---|---|---|"]
    for rel in sorted(prov["records"]):
        if not rel.endswith(("_Implementation.json", "YieldVault.json", "YieldVault_test.json", "DefaultProxyAdmin.json")):
            continue
        ident, rc, oc = source_identity(prov, rel)
        lines.append(f"| `{rel[12:]}` | {ident} | {rc} | {oc} |")
    hist = prov.get("implementation_history") or {}
    if hist:
        lines += ["", "## Implementation history (from Upgraded logs)", ""]
        for chain, rows in sorted(hist.items()):
            if not isinstance(rows, dict) or "status" in rows:
                lines.append(f"- {chain}: {rows}")
                continue
            for proxy, h in rows.items():
                steps = ", ".join(f"{short(x['implementation'])}@{x['block']}" +
                                  (f" ({', '.join(r.split('/')[-1] for r in x['matching_records'])})" if x["matching_records"]
                                   else " (no record)") for x in h["history"])
                lines.append(f"- {chain} {h['kind']} {short(proxy)}: {steps}")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        p = common.run_check(OUT, text)
        print(p or "deployed_doc --check: no differences")
        return 1 if p else 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(text)
    print(f"wrote {os.path.relpath(OUT, common.REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
