#!/usr/bin/env python3
"""Generate tests/helpers/LegacyInterfaces.sol from the *recorded* ABIs.

Legacy tests must talk to recorded bytecode through the ABI it was deployed
with, never through HEAD sources. Interfaces are produced by `cast interface`
from deployments/<chain>/<record>.json; the struct libraries that cast emits
(`VToken`, `YieldVault`) are renamed to `Legacy*Types` so they cannot be
confused with, or clash with, the current contracts.

Usage: legacy_interfaces.py [--check]
"""

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))

import common  # noqa: E402

OUT = common.repo_path("tests", "helpers", "LegacyInterfaces.sol")

INTERFACES = [
    ("mainnet/StPROS_Implementation", "ILegacyStPROSV1"),
    ("mainnet/Oracle_Implementation", "ILegacyOracleV1"),
    ("mainnet/DefaultProxyAdmin", "ILegacyProxyAdminV4"),
    ("mainnet/StPROS_Proxy", "ILegacyTransparentProxyV4"),
    ("mainnet/YieldVaultFactory_Implementation", "ILegacyYieldVaultFactoryV1"),
    ("mainnet/YieldVault", "ILegacyYieldVaultV1"),
    ("testnet/StPROS_Implementation", "ILegacyStPROSV3"),
    ("testnet/Oracle_Implementation", "ILegacyOracleV3"),
    ("testnet/BridgeVault_Implementation", "ILegacyBridgeVaultV3"),
    ("testnet/SlpDistributor_Implementation", "ILegacySlpDistributorV3"),
    ("testnet/YieldVaultFactory_Implementation", "ILegacyYieldVaultFactoryV3"),
    ("testnet/YieldVault", "ILegacyYieldVaultV3"),
]

VERSION_TAG = {"V1": "V1", "V3": "V3", "V4": "V4"}


def cast_interface(record, name):
    abi = common.read_json(common.repo_path("deployments", record + ".json"))["abi"]
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as fh:
        json.dump(abi, fh)
        path = fh.name
    try:
        out = common.run_foundry(["cast", "interface", "-n", name, path]).decode()
    finally:
        os.unlink(path)
    return out


def split_units(src):
    """Return list of (kind, name, text) top-level units after the pragma."""
    body = src.split("\n", 2)[2]  # drop SPDX + pragma
    units = []
    for m in re.finditer(r"^(library|interface) (\w+) \{.*?^\}", body, re.S | re.M):
        units.append((m.group(1), m.group(2), m.group(0)))
    return units


def library_members(text):
    """Members of a cast-emitted library: `type X is ...;` lines and struct blocks."""
    body = text[text.index("{") + 1:text.rindex("}")]
    return [m.group(0).strip() for m in re.finditer(r"^    type [^\n]*;|^    struct \w+ \{.*?^    \}", body, re.S | re.M)]


def generate():
    libs = {}
    ifaces = []
    for record, name in INTERFACES:
        ver = VERSION_TAG[name[-2:]]
        src = cast_interface(record, name)
        # Rename every emitted library (e.g. VToken, YieldVault, Math) to an
        # unambiguous Legacy<Name><Version>Types.
        for old in re.findall(r"^library (\w+) \{", src, re.M):
            src = re.sub(rf"\b{old}\b(?=[ .])", f"Legacy{old}{ver}Types", src)
        for kind, uname, text in split_units(src):
            if kind == "library":
                members = libs.setdefault(uname, [])
                for mem in library_members(text):
                    if mem not in members:
                        members.append(mem)
            else:
                ifaces.append((record, text))
    head = [
        "// SPDX-License-Identifier: GPL-3.0",
        "// GENERATED by tools/release/legacy_interfaces.py from the recorded ABIs in deployments/.",
        "// Do not edit. Regenerate with `python3 tools/release/legacy_interfaces.py`.",
        "pragma solidity ^0.8.28;",
        "",
    ]
    parts = list(head)
    for k in sorted(libs):
        types = sorted(m for m in libs[k] if m.startswith("type "))
        structs = sorted(m for m in libs[k] if m.startswith("struct "))
        inner = "\n\n".join("    " + m for m in types + structs) if types or structs else ""
        parts.append(f"library {k} {{\n{inner}\n}}\n")
    for record, text in ifaces:
        parts.append(f"/// @dev ABI of deployments/{record}.json")
        parts.append(text + "\n")
    return "\n".join(parts).rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = generate()
    if args.check:
        p = common.run_check(OUT, text)
        print(p or "legacy_interfaces --check: no differences")
        return 1 if p else 0
    with open(OUT, "w") as fh:
        fh.write(text)
    print(f"wrote {os.path.relpath(OUT, common.REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
